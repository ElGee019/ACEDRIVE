using AceDrive.Core;

namespace AceDrive.Overlay.Services;

/// <summary>
/// The offline valuation board: no Firebase configured, so the list is empty
/// and the weekly entry stays local. Unity's screen still opens and compares
/// against the local house entry; nothing here reports a rival.
/// </summary>
public sealed class OfflineValuationBoard : IValuationBoard
{
    public bool IsOnline => false;

    public string? OwnUid => null;

    public event Action<IReadOnlyList<ValuationEntry>>? Changed
    {
        add { }
        remove { }
    }

    public Task<IReadOnlyList<ValuationEntry>?> ListAsync(
        CancellationToken cancellationToken = default) =>
        Task.FromResult<IReadOnlyList<ValuationEntry>?>([]);

    public Task<bool> PushEntryAsync(
        string playerName, string carKey, int jobsWithCar,
        double engineBrokenPercent, double score,
        CancellationToken cancellationToken = default) =>
        Task.FromResult(true);

    public Task<bool> WipeOwnAsync(CancellationToken cancellationToken = default) =>
        Task.FromResult(true);

    public void StartWatching()
    {
        // Nothing to watch: the house entry is generated by the flow.
    }

    public void StopWatching()
    {
    }
}
